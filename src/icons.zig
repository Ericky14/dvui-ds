/// Lucide icons — full icon set embedded from SVG files.
///
/// Icons are embedded via @embedFile at comptime and converted to TVG at runtime
/// via dvui.svgToTvg(). Only icons actually referenced in code are included in the binary.
///
/// Use `resolve()` to get cached TVG bytes for drawing with dvui.icon().
///
/// Icon source: https://lucide.dev (1700+ icons)
/// All icons use 24x24 viewBox, stroke-width="2", stroke-linecap="round", stroke-linejoin="round"
const std = @import("std");
const dvui = @import("dvui");

/// Cached TVG bytes for a resolved icon.
pub const Resolved = struct {
    name: [:0]const u8,
    tvg_bytes: []const u8,
};

/// Resolve an SVG icon to cached TVG bytes. Returns null if TVG conversion fails.
/// Uses dvui's per-widget data cache so the conversion only happens once per icon per session.
pub fn resolve(comptime name: [:0]const u8, svg: []const u8) ?Resolved {
    if (!dvui.useTvg) return null;

    const id = dvui.Id.extendId(null, @src(), @as(usize, @intFromPtr(name.ptr)));

    if (dvui.dataGetSlice(null, id, "_tvg", []u8)) |cached| {
        return .{ .name = name, .tvg_bytes = cached };
    }

    const cw = dvui.currentWindow();
    const tvg_bytes = dvui.svgToTvg(cw.arena(), svg) catch |err| {
        std.log.warn("SVG→TVG conversion failed for '{s}': {}", .{ name, err });
        return null;
    };
    defer cw.arena().free(tvg_bytes);
    dvui.dataSetSlice(null, id, "_tvg", tvg_bytes);

    return if (dvui.dataGetSlice(null, id, "_tvg", []u8)) |stored|
        .{ .name = name, .tvg_bytes = stored }
    else
        null;
}

